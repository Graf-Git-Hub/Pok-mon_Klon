// Deterministic battle-state regressions: burn, weakening, guard, regen, isolation.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const env={window:{},Math,console};
const src=fs.readFileSync(path.join(__dirname,'../data/skills.js'),'utf8');
vm.runInNewContext(src,env);
const S=env.window.EchoSkillbook;
const FX=S.STATUS;
assert(FX,'status helper loaded with skillbook');
assert(Object.keys(FX.rules).length>=10);
const creature=(name,hp=100)=>({name,hp,maxHp:100});
const burnBattle={},fire=creature('fire'),grass=creature('grass');
assert.equal(FX.apply(burnBattle,fire,grass,'kohlenregen',()=>0),'BRAND');
assert.match(FX.labels(burnBattle,grass),/BRAND/);
assert.equal(FX.endAction(burnBattle,grass),'BRAND -5 KP');
assert.equal(grass.hp,95);
assert.equal(FX.endAction(burnBattle,grass),'BRAND -5 KP');
assert.equal(FX.endAction(burnBattle,grass),'BRAND -5 KP');
assert.equal(FX.endAction(burnBattle,grass),'');
assert.equal(grass.hp,85);
// Damage-over-time alone may not KO: no unexpected skip of boss/quest callbacks.
const nearlyFainted=creature('weak',2),b2={};
FX.apply(b2,fire,nearlyFainted,'kohlenregen',()=>0);
FX.endAction(b2,nearlyFainted);
assert.equal(nearlyFainted.hp,1);
const cleanBattle={};
assert.equal(FX.labels(cleanBattle,grass),'','statuses never leak into the next battle');
const shieldBattle={},stone=creature('stone'),foe=creature('foe');
assert.equal(FX.apply(shieldBattle,stone,foe,'steinmantel',()=>0),'SCHUTZ');
assert.equal(FX.adjustedDamage(shieldBattle,foe,stone,100),65);
assert.equal(FX.adjustedDamage(shieldBattle,foe,stone,100),100,'guard expires after one hit');
const other=creature('other');
FX.apply(shieldBattle,stone,foe,'steinmantel',()=>0);
assert.equal(FX.adjustedDamage(shieldBattle,foe,other,100),100,'guard belongs to one creature');
assert.equal(FX.adjustedDamage(shieldBattle,foe,stone,100),65);
const frostBattle={},ice=creature('ice'),target=creature('target');
assert.equal(FX.apply(frostBattle,ice,target,'winterkrone',()=>0),'FROST');
assert.equal(FX.adjustedDamage(frostBattle,target,ice,100),80);
FX.endAction(frostBattle,target);
assert.equal(FX.adjustedDamage(frostBattle,target,ice,100),80);
FX.endAction(frostBattle,target);
assert.equal(FX.adjustedDamage(frostBattle,target,ice,100),100,'frost expires after 2 actions');
assert.equal(FX.labels(frostBattle,target),'');
const lightningBattle={};
assert.equal(FX.apply(lightningBattle,ice,target,'gewitterherz',()=>.99),'','chance respected');
assert.equal(FX.apply(lightningBattle,ice,target,'gewitterherz',()=>0),'SCHOCK');
assert.match(FX.labels(lightningBattle,target),/SCHOCK/);
const healBattle={},nature=creature('nature',50);
assert.equal(FX.apply(healBattle,nature,foe,'waldsegen',()=>0),'NACHKLANG');
assert.equal(FX.endAction(healBattle,nature),'NACHKLANG +5 KP');
assert.equal(FX.endAction(healBattle,nature),'NACHKLANG +5 KP');
assert.equal(FX.endAction(healBattle,nature),'');
assert.equal(nature.hp,60);
const full=creature('full',99),b4={};
FX.apply(b4,full,foe,'waldsegen',()=>0);
FX.endAction(b4,full);FX.endAction(b4,full);
assert.equal(full.hp,100,'regen never exceeds max health');
// Rune skills use the same rules as naturally learned skills.
assert.equal(FX.apply({},nature,foe,'pfotentanz',()=>0),'SCHUTZ');
console.log('COMBAT_STATUS_PASS',JSON.stringify({rules:Object.keys(FX.rules).length,burnTurns:3,frostTurns:2,guardReduction:35,regenTicks:2}));
